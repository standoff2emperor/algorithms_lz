import random
#создание пустого списка для 
list = []
while len(list) < 100:
    a = random.randint(0, 1000000)
    if a not in list: 
        list.append(a)
#сортировка полученного списка по возрастанию
list.sort()
print(list)
#линейному поиск
lin_list=list
print("введите искомое число")
b = int(input())#вводим с клавиатуры искомое число
c = 0#счетчик количества сравнений для линейного поиска
d = 0#переменная для нахождения элемента (0 - не найден, 1 - найден)
# Выполнение алгоритма линейного поиска
for i in range(len(lin_list)):
    c+=1
    if lin_list[i] == b: 
        d+=1
        break
if d==0: 
    print("нет элемента")
#бинарный поиск 
e = 0# Счетчик количества сравнений для бинарного поиска
f = 0# Флаг успешного нахождения (0 - не найден, 1 - найден)
bin_list = list# Ссылка на исходный отсортированный список
first=0#Левая граница поиска 
last=len(bin_list) - 1#правая граница поиска 
index=-1#индекс найденного элемента (-1 означает, что элемент пока не найден)
#выполнение алгоритма бинарного поиска
while (index == -1) and (first <= last):
    mid=(first + last) // 2
    e+=1
    if bin_list[mid] == b: 
        index = mid
        f+=1
    elif b < bin_list[mid]: 
        last=mid - 1
    else: 
        first=mid + 1
if f==0: 
    print("нет элемента")
# Вывод результатов работы программы
print("индекс элемента",index)
print("количество сравнений линейного поиска", c)
print("количество сравнений бинарного поиска", e)